#!/bin/bash
################################################################################
# Emailサブスクリプション設定スクリプト
#
# - 対象トピック: ts-010-sns-010
# - プロトコル: email
# - エンドポイント(Eメールアドレス)はコマンドライン引数で指定
################################################################################
set -euo pipefail
MY_NAME=${0##*/}
LOG_PATH=./${MY_NAME}.log

exec >> "${LOG_PATH}" 2>&1

# --- 設定 --- #
TOPIC_NAME="ts-010-sns-010"

################################################################################
# メイン処理
################################################################################
echo "実行開始: $(date)"
echo "------------------------------------------------------------"

# 引数チェック
if [ $# -ne 1 ]; then
  echo "エラー: Eメールアドレスを引数として指定してください (例: user@example.com)"
  exit 1
fi
EMAIL_ADDRESS=$1
echo "指定されたEメールアドレス: $EMAIL_ADDRESS"

# トピックのARNを取得
echo "--- SNSトピック [$TOPIC_NAME] のARNを取得します ---"
TOPIC_ARN=$(aws sns list-topics | grep "$TOPIC_NAME" | awk '{print $2}' | tr -d '"')
if [ -z "$TOPIC_ARN" ]; then
  echo "エラー: SNSトピック [$TOPIC_NAME] が見つかりません。先にトピックを作成してください。"
  exit 1
fi
echo "トピックARN: $TOPIC_ARN"

# サブスクリプション設定
echo "--- サブスクリプションを設定します ---"
aws sns subscribe \
  --topic-arn "$TOPIC_ARN" \
  --protocol email \
  --notification-endpoint "$EMAIL_ADDRESS"

echo "サブスクリプションのリクエストを送信しました。"
echo "AWSから確認用のEメールが届きますので、メール内のリンクをクリックして承認してください。"

echo "------------------------------------------------------------"
echo "実行終了: $(date)"

exit 0
