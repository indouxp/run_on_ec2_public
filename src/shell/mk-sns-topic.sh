#!/bin/bash
################################################################################
# SNSトピック作成スクリプト
#
# - トピック名: ts-010-sns-010
# Last updated: 2026-03-26 20:42:27
################################################################################
set -euo pipefail
MY_NAME=${0##*/}
LOG_PATH=./${MY_NAME}.log

exec >> "${LOG_PATH}" 2>&1

# --- 設定 --- #
TOPIC_NAME="ts-010-sns-010"

################################################################################
# 確認
################################################################################
confirm_topic() {
  echo "############################################################"
  echo "# SNSトピック [$TOPIC_NAME] の設定確認"
  echo "############################################################"
  
  aws sns list-topics | grep "$TOPIC_NAME" || echo "SNSトピック [$TOPIC_NAME] は存在しません。"
  echo
}

################################################################################
# 作成処理
################################################################################
create_topic() {
  echo "############################################################"
  echo "# SNSトピック [$TOPIC_NAME] の作成処理"
  echo "############################################################"

  if aws sns list-topics | grep -q "$TOPIC_NAME"; then
    echo "SNSトピック [$TOPIC_NAME] は既に存在します。削除して再作成します。"
    TOPIC_ARN=$(aws sns list-topics --query 'Topics[].TopicArn' --output text | tr '\t' '\n' | grep "${TOPIC_NAME}")
    aws sns delete-topic --topic-arn "$TOPIC_ARN"
    echo "SNSトピック [$TOPIC_NAME] を削除しました。"
  fi
  echo "SNSトピック [$TOPIC_NAME] を新規作成します。"
  TOPIC_ARN=$(aws sns create-topic --name "$TOPIC_NAME" --query 'TopicArn' --output text)
  aws sns tag-resource --resource-arn "$TOPIC_ARN" \
    --tags "Key=${PRJ_TAG_KEY},Value=${PRJ_TAG_VALUE}"

  echo "処理完了。トピックARN: $TOPIC_ARN"
  echo
}

################################################################################
# サブスクリプション再設定の警告
#
# SNSトピックを削除→再作成すると、登録済みのサブスクリプション
# （Email・SMS）がすべて失われる。
# サブスクリプションは宛先（メールアドレス・電話番号）の引数が必要なため
# 自動再設定できない。完了後に手動で再設定すること。
################################################################################
warn_subscriptions() {
  echo "############################################################"
  echo "# [WARN] サブスクリプションの再設定が必要です"
  echo "############################################################"
  echo "SNSトピックを再作成したため、サブスクリプションが失われました。"
  echo "以下のコマンドを手動で実行してください:"
  echo "  set-email-subscription.sh <メールアドレス>"
  echo "  set-sms-subscription.sh   <電話番号（例: +819012345678）>"
  echo
}

################################################################################
# メイン処理
################################################################################
echo "実行開始: $(date)"
echo "------------------------------------------------------------"

confirm_topic
create_topic
# SNSトピック再作成後はサブスクリプションが失われるため、手動再設定を促す
warn_subscriptions
confirm_topic

echo "------------------------------------------------------------"
echo "実行終了: $(date)"

exit 0
